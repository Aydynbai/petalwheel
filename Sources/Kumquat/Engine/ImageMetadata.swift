import Foundation
import ImageIO

/// Metadata removal for images.
enum ImageMetadata {
    /// Keys that must not survive a strip.
    static let privateKeys: [CFString] = [kCGImagePropertyExifDictionary, kCGImagePropertyGPSDictionary,
                                          kCGImagePropertyIPTCDictionary, kCGImagePropertyMakerAppleDictionary,
                                          kCGImagePropertyExifAuxDictionary]

    static func strip(_ url: URL) async throws -> URL {
        guard let format = FileFormat.detect(url), format.isRasterImage else {
            throw KumquatError(l: "Can't remove metadata from %@.", url.lastPathComponent)
        }
        let out = OutputNaming.url(for: url, ext: format.fileExtension, suffix: "clean")
        // Lossless path for JPEG / PNG / TIFF / HEIC: copy the image data, replace the metadata.
        if [.jpg, .png, .tiff, .heic, .avif].contains(format), losslessStrip(url, to: out), isClean(out) {
            return out
        }
        try? FileManager.default.removeItem(at: out)
        // Fallback: decode (orientation applied) and re-encode without metadata.
        let loaded = try ImageCodec.load(url, format: format)
        let target: FileFormat = format == .webp && !ExternalTools.shared.hasWebPEncoder ? .png : format
        let finalOut = target == format ? out : OutputNaming.url(for: url, ext: target.fileExtension, suffix: "clean")
        try await ImageCodec.write(loaded.image, to: finalOut, format: target, quality: 0.95, metadata: nil)
        return finalOut
    }

    private static func losslessStrip(_ url: URL, to out: URL) -> Bool {
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let type = CGImageSourceGetType(src),
              CGImageSourceGetCount(src) == 1 else { return false }
        let props = (CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any]) ?? [:]
        let orientation = (props[kCGImagePropertyOrientation] as? NSNumber)?.intValue ?? 1
        let meta = CGImageMetadataCreateMutable()
        if orientation != 1 {
            // Keep only the orientation so the picture still displays upright.
            CGImageMetadataSetValueMatchingImageProperty(meta, kCGImagePropertyTIFFDictionary,
                                                         kCGImagePropertyTIFFOrientation, orientation as CFNumber)
        }
        guard let dest = CGImageDestinationCreateWithURL(out as CFURL, type, 1, nil) else { return false }
        let options: [CFString: Any] = [
            kCGImageDestinationMetadata: meta,
            kCGImageDestinationMergeMetadata: false,
            kCGImageMetadataShouldExcludeGPS: true,
            kCGImageMetadataShouldExcludeXMP: orientation == 1,
        ]
        var error: Unmanaged<CFError>?
        let ok = CGImageDestinationCopyImageSource(dest, src, options as CFDictionary, &error)
        return ok
    }

    /// Verifies that no EXIF/GPS/IPTC (beyond technical basics) is left.
    static func isClean(_ url: URL) -> Bool {
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] else { return false }
        if props[kCGImagePropertyGPSDictionary] != nil || props[kCGImagePropertyIPTCDictionary] != nil
            || props[kCGImagePropertyMakerAppleDictionary] != nil { return false }
        if let exif = props[kCGImagePropertyExifDictionary] as? [CFString: Any] {
            // Pixel dimensions / colour space may be regenerated by ImageIO; anything personal is a fail.
            let harmless: Set<String> = [kCGImagePropertyExifPixelXDimension as String,
                                         kCGImagePropertyExifPixelYDimension as String,
                                         kCGImagePropertyExifColorSpace as String]
            if exif.keys.contains(where: { !harmless.contains($0 as String) }) { return false }
        }
        if let tiff = props[kCGImagePropertyTIFFDictionary] as? [CFString: Any] {
            let personal: [CFString] = [kCGImagePropertyTIFFMake, kCGImagePropertyTIFFModel, kCGImagePropertyTIFFArtist,
                                        kCGImagePropertyTIFFSoftware, kCGImagePropertyTIFFDateTime,
                                        kCGImagePropertyTIFFCopyright, kCGImagePropertyTIFFHostComputer]
            if personal.contains(where: { tiff[$0] != nil }) { return false }
        }
        if let meta = CGImageSourceCopyMetadataAtIndex(src, 0, nil),
           let tags = CGImageMetadataCopyTags(meta) as? [CGImageMetadataTag] {
            for tag in tags {
                let prefix = CGImageMetadataTagCopyPrefix(tag) as String? ?? ""
                if !["tiff", "exif", "iio"].contains(prefix) { return false }
            }
        }
        return true
    }
}
